import {createClient} from '@supabase/supabase-js';
import {readFile,writeFile} from 'node:fs/promises';
const path='.local-backups/media-e2e-20261025/customer.json';
const state=JSON.parse(await readFile(path,'utf8'));
const admin=createClient(process.env.SUPABASE_URL,process.env.SUPABASE_SERVICE_ROLE_KEY,{auth:{persistSession:false}});
const {data:account,error}=await admin.auth.admin.getUserById(state.id);
if(error) throw error;
if(account.user.email!==state.email||!state.email.startsWith('codex.media.')||account.user.user_metadata.full_name!=='DUMMY MEDIA TEST 20261025') throw new Error('Dummy account identity mismatch; nothing deleted');
const own=createClient(process.env.EXPO_PUBLIC_SUPABASE_URL,process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY,{auth:{persistSession:false}});
const {data:session,error:loginError}=await own.auth.signInWithPassword({email:state.email,password:state.password});
if(loginError) throw loginError;
const {data:reviews,error:reviewError}=await own.from('reviews').select('id').eq('profile_id',state.id);
if(reviewError||reviews.length) throw new Error('Dummy review cleanup must complete first');
const {data:profile,error:profileError}=await own.from('profiles').select('profile_image').eq('id',state.id).single();
if(profileError||profile.profile_image) throw new Error('Dummy profile media cleanup must complete first');
const verification=await Promise.all(state.uploads.filter(item=>item.url).map(async item=>({publicId:item.publicId,status:(await fetch(item.url,{method:'HEAD'})).status})));
if(verification.some(item=>item.status!==404)) throw new Error('Known dummy image assets remain; account preserved for cleanup');
const {error:signOutError}=await admin.auth.admin.signOut(session.session.access_token,'global');
if(signOutError) throw signOutError;
const {error:deleteError}=await admin.auth.admin.deleteUser(state.id);
if(deleteError) throw deleteError;
state.password='';state.cleanup={accountDeleted:true,knownImages:verification};
await writeFile(path,JSON.stringify(state,null,2),{mode:0o600});
console.log(JSON.stringify(state.cleanup));
